function readme({ name, motd, maxPlayers, port, edition }) {
  const proto = edition === 'java' ? 'tcp' : 'udp';
  return `# ${name} — host pack

Generated by Omlet Arcade. This pack configures a ${edition === 'java' ? 'Java' : 'Bedrock'} dedicated
server and hardens the machine it runs on. The app never runs the game for you:
you run it here, then set the server to Running in the app so your friends see
the address and the voice room.

## 1. Get the server binary

${edition === 'java'
    ? 'Download the official server jar from minecraft.net and drop it in this folder.'
    : 'Download the Bedrock Dedicated Server archive from minecraft.net, unpack it into\nthis folder so `bedrock_server` sits next to `start.sh`, then `chmod +x bedrock_server`.'}

## 2. Configure

- \`server.properties\` is pre-filled: name "${name}", port ${port}, ${maxPlayers} players.
- \`allow-list=true\` is on. Add your friends in the app (or edit whitelist.json),
  not by turning the allow-list off — an open list is how strangers join.

## 3. Harden the machine

    sudo ./iptables.rules

That caps new connections per source (${proto}/${port}) so one flood cannot take the box down.
Optional but recommended:

    sudo cp fail2ban-jail.conf /etc/fail2ban/jail.d/omlet-game.conf
    sudo systemctl restart fail2ban

## 4. Run

    chmod +x start.sh stop.sh watchdog.sh
    ./start.sh

\`watchdog.sh\` restarts the server if it dies, and gives up after 5 crashes in
10 minutes instead of spinning forever. To run it as a service:

    sudo useradd -r -d /opt/minecraft minecraft
    sudo cp -r . /opt/minecraft && sudo chown -R minecraft:minecraft /opt/minecraft
    sudo cp omlet-minecraft.service /etc/systemd/system/
    sudo systemctl enable --now omlet-minecraft

## 5. Tell the app

In Omlet Arcade: Minecraft > your server > set status to Running. Your friends
get the address (\`<your-public-ip>:${port}\`) and a voice room that stays open
while they play.

## Troubleshooting

- Port not reachable: open ${proto}/${port} in the cloud firewall too, not only here.
- Behind NAT: forward ${proto}/${port} to this machine, or rent a small VPS.
- Voice but no game: the voice room uses the app's own transport, it does not
  depend on this server being reachable.
- MOTD shows as "${motd}".

## What this pack never does

It sends no telemetry, opens no inbound port besides ${proto}/${port} and SSH,
and stores no credentials. Voice runs through the app, not through this box.
`;
}

function build({ name, motd, maxPlayers, port, edition }) {
  const proto = edition === 'java' ? 'tcp' : 'udp';
  const firewall = FIREWALL.replace(/__PORT__/g, String(port)).replace(/__PROTO__/g, proto);
  const files = [
    { name: 'README.md', data: readme({ name, motd, maxPlayers, port, edition }) },
    { name: 'start.sh', data: edition === 'java' ? START_JAVA : START_BEDROCK, mode: 0o755 },
    { name: 'stop.sh', data: STOP, mode: 0o755 },
    { name: 'watchdog.sh', data: WATCHDOG, mode: 0o755 },
    { name: 'iptables.rules', data: firewall, mode: 0o755 },
    { name: 'fail2ban-jail.conf', data: FAIL2BAN.replace(/__PORT__/g, String(port)).replace(/__PROTO__/g, proto) },
    { name: 'omlet-minecraft.service', data: SYSTEMD },
  ];
  if (edition === 'java') {
    files.push(
      { name: 'server.properties', data: javaProperties({ name, motd, maxPlayers, port }) },
      { name: 'whitelist.json', data: WHITELIST },
      { name: 'ops.json', data: '[]\n' },
      { name: 'eula.txt', data: '# Read and accept the Minecraft EULA, then set this to true.\neula=false\n' },
    );
  } else {
    files.push(
      { name: 'server.properties', data: bedrockProperties({ name, motd, maxPlayers, port }) },
      { name: 'allowlist.json', data: WHITELIST },
      { name: 'permissions.json', data: PERMISSIONS },
      { name: 'valid_known_packs.json', data: '[{"pack_id":"vanilla","version":"1.0.0"}]\n' },
    );
  }
  files.push({
    name: 'VERSION',
    data: `pack=1.0.0\nedition=${edition}\nmax_players=${maxPlayers}\nport=${port}\nserver_slots_cap=${config.minecraft.maxSlots}\n`,
  });
  return files;
}

module.exports = { build, bedrockProperties, javaProperties };
