const START_BEDROCK = `#!/usr/bin/env bash
# Start the Bedrock dedicated server under a watchdog. Idempotent.
set -euo pipefail
cd "$(dirname "$0")"
BIN=./bedrock_server
[ -x "$BIN" ] || { echo "Download the Bedrock dedicated server into this folder first (see README.md)."; exit 1; }
mkdir -p logs
if [ -f server.pid ] && kill -0 "$(cat server.pid)" 2>/dev/null; then
  echo "Already running (pid $(cat server.pid))."; exit 0
fi
LD_LIBRARY_PATH=. nohup "$BIN" >> "logs/server-$(date +%Y%m%d-%H%M%S).log" 2>&1 &
echo $! > server.pid
echo "Started with pid $(cat server.pid)."
echo "Now set the server status to Running in the app so your friends can see it."
`;

const START_JAVA = `#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"
JAR=$(ls -1 *.jar 2>/dev/null | grep -v -e '^libraries$' | head -n1 || true)
[ -n "$JAR" ] || { echo "Put the server jar in this folder first (see README.md)."; exit 1; }
mkdir -p logs
if [ -f server.pid ] && kill -0 "$(cat server.pid)" 2>/dev/null; then
  echo "Already running (pid $(cat server.pid))."; exit 0
fi
nohup java -Xms1G -Xmx2G -XX:+UseG1GC -XX:+ParallelRefProcEnabled -XX:MaxGCPauseMillis=200 \\
  -jar "$JAR" nogui >> "logs/server-$(date +%Y%m%d-%H%M%S).log" 2>&1 &
echo $! > server.pid
echo "Started with pid $(cat server.pid)."
`;

const STOP = `#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"
[ -f server.pid ] || { echo "Not running."; exit 0; }
PID=$(cat server.pid)
if kill -0 "$PID" 2>/dev/null; then
  kill -TERM "$PID"
  for _ in $(seq 1 30); do kill -0 "$PID" 2>/dev/null || break; sleep 1; done
  kill -0 "$PID" 2>/dev/null && kill -KILL "$PID" || true
  echo "Stopped."
else
  echo "Stale pid file."
fi
rm -f server.pid
`;

const WATCHDOG = `#!/usr/bin/env bash
# Restarts the server when it dies, with backoff so a crash loop cannot spin.
set -uo pipefail
cd "$(dirname "$0")"
MAX_RESTARTS=5
WINDOW=600
declare -a TIMES=()
while true; do
  if [ -f server.pid ] && kill -0 "$(cat server.pid)" 2>/dev/null; then
    sleep 10; continue
  fi
  NOW=$(date +%s)
  TIMES+=("$NOW")
  TIMES=($(for t in "\${TIMES[@]}"; do [ $((NOW - t)) -lt $WINDOW ] && echo "$t"; done))
  if [ "\${#TIMES[@]}" -ge $MAX_RESTARTS ]; then
    echo "[$(date -Is)] $MAX_RESTARTS crashes in \${WINDOW}s: giving up. Check logs/." >&2
    exit 1
  fi
  echo "[$(date -Is)] server down, restarting (attempt \${#TIMES[@]}/$MAX_RESTARTS)"
  ./start.sh || true
  sleep 15
done
`;

const FIREWALL = `#!/usr/bin/env bash
# Connection-rate rules for a game host. Run once as root: sudo ./iptables.rules
# The CONNLIMIT and HASHLIMIT rules are what stops a single flood from taking
# the box down; they cap new connections per source instead of banning it.
set -euo pipefail
GAME_PORT=__PORT__          # UDP for Bedrock, TCP for Java
GAME_PROTO=__PROTO__
SSH_PORT=22

iptables -N OMLET_GAME 2>/dev/null || iptables -F OMLET_GAME

# Drop packets that belong to no connection.
iptables -A OMLET_GAME -m conntrack --ctstate INVALID -j DROP
# Never more than 12 concurrent connections from one source.
iptables -A OMLET_GAME -m connlimit --connlimit-above 12 --connlimit-mask 32 -j DROP
# Never more than 20 new connections per minute from one source.
iptables -A OMLET_GAME -m hashlimit --hashlimit-name game --hashlimit-above 20/min \\
  --hashlimit-burst 8 --hashlimit-mode srcip -j DROP
# Global new-connection ceiling so the box stays reachable.
iptables -A OMLET_GAME -m conntrack --ctstate NEW -m limit --limit 60/s --limit-burst 120 -j ACCEPT
iptables -A OMLET_GAME -j DROP

iptables -C INPUT -p __PROTO__ --dport $GAME_PORT -j OMLET_GAME 2>/dev/null || \\
  iptables -I INPUT -p __PROTO__ --dport $GAME_PORT -j OMLET_GAME

# Keep SSH alive and rate limited.
iptables -C INPUT -p tcp --dport $SSH_PORT -m conntrack --ctstate NEW -m limit --limit 5/min --limit-burst 10 -j ACCEPT 2>/dev/null || \\
  iptables -I INPUT -p tcp --dport $SSH_PORT -m conntrack --ctstate NEW -m limit --limit 5/min --limit-burst 10 -j ACCEPT

# Persist across reboots (Debian/Ubuntu: apt install iptables-persistent).
command -v netfilter-persist >/dev/null 2>&1 && netfilter-persist save || \\
  echo "Install iptables-persistent to keep these rules across reboots."
echo "Rules applied for $GAME_PROTO/$GAME_PORT."
`;

