'use strict';
/**
 * Storage layer. One query interface over two drivers:
 *   - postgres (`pg`)  -> production on Render
 *   - sqlite (better-sqlite3) -> local runs and the test suite
 *
 * Every statement is parameterized. There is no string interpolation of user
 * input into SQL anywhere in this project; `sql` only ever rewrites dialect
 * syntax, never values.
 */
const fs = require('node:fs');
const path = require('node:path');
const { config } = require('./config');

let driverName = config.db.driver;
let impl = null;

function translate(sqlText) {
  if (driverName !== 'pg' || !sqlText.includes('?')) return sqlText;
  let index = 0;
  return sqlText.replace(/\?/g, () => `$${++index}`);
}

/** Dialect helpers. Keep them tiny; anything bigger belongs in the caller. */
const sql = {
  /** All timestamps are epoch milliseconds in INTEGER columns (no dialect surprises). */
  now: () => Date.now(),
  bool: (value) => (driverName === 'pg' ? !!value : value ? 1 : 0),
  int: (value) => Number(value || 0),
  /** pg returns JS booleans, sqlite returns 0/1: normalize on read. */
  asBool: (value) => value === true || value === 1 || value === '1',
  json: (value) => (value === undefined || value === null ? null : JSON.stringify(value)),
  parse: (value) => {
    if (value === null || value === undefined || value === '') return null;
    if (typeof value === 'object') return value;
    try { return JSON.parse(value); } catch { return null; }
  },
  /** `INSERT ... ON CONFLICT (k) DO UPDATE SET a=EXCLUDED.a` (both dialects agree). */
  upsert(table, columns, conflictColumns, updateColumns) {
    const cols = columns.join(', ');
    const marks = columns.map(() => '?').join(', ');
    const setClause = updateColumns.map((c) => `${c}=EXCLUDED.${c}`).join(', ');
    return `INSERT INTO ${table} (${cols}) VALUES (${marks}) ON CONFLICT (${conflictColumns.join(', ')}) DO UPDATE SET ${setClause}`;
  },
  limit: (n, offset) => `LIMIT ${Math.max(0, Math.floor(n))} OFFSET ${Math.max(0, Math.floor(offset))}`,
};

