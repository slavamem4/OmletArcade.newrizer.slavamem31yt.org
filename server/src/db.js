/* ----------------------------------------------------------------- drivers */

function createSqlite() {
  const Database = require('better-sqlite3');
  fs.mkdirSync(path.dirname(config.db.sqliteFile), { recursive: true });
  const handle = new Database(config.db.sqliteFile);
  handle.pragma('journal_mode = WAL');
  handle.pragma('foreign_keys = ON');
  handle.pragma('busy_timeout = 5000');
  return {
    name: 'sqlite',
    // better-sqlite3 is synchronous; wrapping in Promise.resolve keeps every
    // call site identical to the pg driver (await works on both).
    query: (text, params = []) => Promise.resolve(handle.prepare(translate(text)).all(...params)),
    get: (text, params = []) => Promise.resolve(handle.prepare(translate(text)).get(...params) || null),
    run: (text, params = []) => {
      const info = handle.prepare(translate(text)).run(...params);
      return Promise.resolve({ changes: info.changes, insertId: Number(info.lastInsertRowid) });
    },
    exec: (text) => { handle.exec(text); return Promise.resolve(); },
    transaction: async (fn) => {
      const tx = handle.transaction(() => fn());
      return tx();
    },
    close: () => handle.close(),
    file: config.db.sqliteFile,
  };
}

function createPg() {
  const pg = require('pg');
  // node-postgres returns BIGINT (int8) and NUMERIC as strings to avoid
  // precision loss. Every id in this app fits in a double, and callers compare
  // them with ===, so parse them back to numbers like SQLite does.
  pg.types.setTypeParser(pg.types.builtins.INT8, (v) => (v === null ? null : parseInt(v, 10)));
  pg.types.setTypeParser(pg.types.builtins.NUMERIC, (v) => (v === null ? null : parseFloat(v)));
  const { Pool } = pg;
  const pool = new Pool({
    connectionString: config.db.url,
    max: config.db.poolMax,
    statement_timeout: config.db.statementTimeoutMs,
    ssl: /localhost|127\.0\.0\.1/.test(config.db.url) ? false : { rejectUnauthorized: false },
  });
  pool.on('error', (err) => {
    // An idle client dropped (Render restarts Postgres on idle). Log and let
    // the pool replace it; do not crash the process.
    require('./logger').warn('pg idle client error', { message: err.message });
  });
  return {
    name: 'pg',
    query: async (text, params = []) => (await pool.query(translate(text), params)).rows,
    get: async (text, params = []) => (await pool.query(translate(text), params)).rows[0] || null,
    run: async (text, params = []) => {
      const result = await pool.query(translate(text), params);
      const insertId = result.rows && result.rows[0] && result.rows[0].id ? Number(result.rows[0].id) : 0;
      return { changes: result.rowCount || 0, insertId };
    },
    exec: async (text) => pool.query(text),
    transaction: async (fn) => {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const scoped = {
          query: async (text, params = []) => (await client.query(translate(text), params)).rows,
          get: async (text, params = []) => (await client.query(translate(text), params)).rows[0] || null,
          run: async (text, params = []) => {
            const result = await client.query(translate(text), params);
            return { changes: result.rowCount || 0, insertId: result.rows[0] ? Number(result.rows[0].id || 0) : 0 };
          },
        };
        const out = await fn(scoped);
        await client.query('COMMIT');
        return out;
      } catch (err) {
        try { await client.query('ROLLBACK'); } catch { /* connection already gone */ }
        throw err;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

/**
 * Insert helpers that must return the new row id on both drivers.
 */
async function insertReturning(table, columns, values) {
  if (driverName === 'pg') {
    const marks = columns.map((_, i) => `$${i + 1}`).join(', ');
    const rows = await impl.query(
      `INSERT INTO ${table} (${columns.join(', ')}) VALUES (${marks}) RETURNING id`,
      values
    );
    return Number(rows[0].id);
  }
  const marks = columns.map(() => '?').join(', ');
  const info = await impl.run(`INSERT INTO ${table} (${columns.join(', ')}) VALUES (${marks})`, values);
  return Number(info.insertId);
}

/**
 * Deployments created before the BIGINT fix hold 4-byte integer timestamp
 * columns. Widen them in place; CREATE TABLE IF NOT EXISTS alone would leave
 * the old shape untouched. integer -> bigint needs no USING clause.
 */
const TS_MIGRATION = [
  ['users', 'locked_until'], ['users', 'last_seen_at'], ['users', 'created_at'], ['users', 'updated_at'],
  ['devices', 'created_at'],
  ['sessions', 'revoked_at'], ['sessions', 'expires_at'], ['sessions', 'created_at'],
  ['friendships', 'created_at'],
  ['blocks', 'created_at'],
  ['parties', 'created_at'], ['parties', 'updated_at'],
  ['party_members', 'joined_at'],
  ['party_invites', 'created_at'],
  ['party_events', 'created_at'],
  ['channels', 'created_at'],
  ['messages', 'created_at'],
  ['mc_servers', 'created_at'], ['mc_servers', 'updated_at'],
  ['mc_sessions', 'joined_at'], ['mc_sessions', 'left_at'],
  ['broadcasts', 'started_at'], ['broadcasts', 'ended_at'],
  ['feed_items', 'created_at'],
  ['notifications', 'read_at'], ['notifications', 'created_at'],
  ['reports', 'created_at'],
  ['bans', 'expires_at'], ['bans', 'created_at'],
  ['wrapped_keys', 'created_at'],
  ['key_packages', 'created_at'],
  ['audit_log', 'created_at'],
  ['purge_log', 'created_at'],
];

async function migratePgTimestamps() {
  for (const [table, column] of TS_MIGRATION) {
    try {
      await impl.exec(`ALTER TABLE ${table} ALTER COLUMN ${column} TYPE BIGINT`);
    } catch (err) {
      require('./logger').warn('timestamp migration skipped', { table, column, message: err.message });
    }
  }
}

async function init() {
  impl = driverName === 'pg' ? createPg() : createSqlite();
  for (const statement of tableDefs()) {
    await impl.exec(statement);
  }
  if (driverName === 'pg') await migratePgTimestamps();
  return impl;
}

function db() {
  if (!impl) throw new Error('db.init() was not called');
  return impl;
}

/** Test helper: switch driver before init (sqlite file in a temp dir). */
function setDriver(name) {
  if (impl) throw new Error('setDriver must run before init');
  driverName = name;
  config.db.driver = name;
}

module.exports = { init, db, sql, insertReturning, setDriver, tableDefs };
